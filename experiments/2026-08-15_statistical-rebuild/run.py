"""WP1 - rebuild the statistics behind the qwen_full headline, without re-running
any inference.

Reads results/<run>/*.json read-only and writes report.md inside this arm's own
directory. scripts/compute_metrics.py and reports/qwen_full_report.md are left
exactly as published; this is a companion analysis, not a replacement.

Three things the published numbers get wrong, corrected here:
  - binomial CIs over cases that are clustered by CVE and repo
  - Pairwise Ranking Accuracy scoring 43% ties as failures
  - an independence baseline that assumes the very independence it argues against

Plus two diagnostics the report does not have: the score/category dependence that
makes ROC-AUC non-independent evidence, and per-stratum breakdowns.

Usage:
    python3 experiments/2026-08-15_statistical-rebuild/run.py [run_name ...]
"""
import difflib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "experiments" / "common"))

import metrics as M  # noqa: E402
from data import load_cases, load_records, scored, to_pairs  # noqa: E402

# The figures reports/qwen_full_report.md publishes. If these stop reproducing,
# something upstream changed and no number below should be trusted.
PUBLISHED = {"qwen_full": {"n_cases": 391, "n_scored": 357, "pfa": 0.160,
                          "roc_auc": 0.475, "n_degenerate": 34}}

REPO_GROUPS = ["torvalds/linux", "chromium/chromium", "ImageMagick/ImageMagick"]


def pct(x, nd=1):
    return "n/a" if x is None else f"{x * 100:.{nd}f}%"


def changed_lines(case):
    v = case["vulnerable_snippet"].splitlines()
    f = case["fixed_snippet"].splitlines()
    d = difflib.unified_diff(v, f, lineterm="", n=0)
    return sum(1 for l in d
               if (l.startswith("+") or l.startswith("-"))
               and not l.startswith(("+++", "---")))


def check_reproduction(run, s, out):
    exp = PUBLISHED.get(run)
    if not exp:
        return True
    ok = True
    for key, want in exp.items():
        got = s[key]
        near = abs(got - want) <= (0.002 if isinstance(want, float) else 0)
        if not near:
            ok = False
        out.append(f"- `{key}`: published {want}, recomputed "
                   f"{got if isinstance(got, int) else round(got, 4)} "
                   f"{'OK' if near else '**MISMATCH**'}")
    return ok


def strata_table(pairs, cases, out):
    def emit(title, groups):
        out.append(f"\n**{title}**\n")
        out.append("| stratum | n scored | PFA | 2AFC (ties excl.) | ROC-AUC |")
        out.append("|---|---|---|---|---|")
        for name, sub in groups:
            sc = scored(sub)
            if not sc:
                continue
            a = M.afc(sub)
            out.append(f"| {name} | {len(sc)} | {pct(M.pfa(sub))} | "
                       f"{pct(a['tie_corrected'])} (n={a['n_untied']}) | "
                       f"{M.auc(sub):.3f} |")

    by_repo = [(r, [p for p in pairs if p.repo == r]) for r in REPO_GROUPS]
    by_repo.append(("all other repos", [p for p in pairs if p.repo not in REPO_GROUPS]))
    emit("By repository", by_repo)

    emit("By language", [(l, [p for p in pairs if p.language == l]) for l in ("c", "cpp")])

    sizes = sorted(changed_lines(cases[p.case_id]) for p in pairs if p.case_id in cases)
    if sizes:
        q = [sizes[int(len(sizes) * f)] for f in (0.25, 0.5, 0.75)]
        bounds = [(0, q[0]), (q[0] + 1, q[1]), (q[1] + 1, q[2]), (q[2] + 1, 10 ** 9)]
        groups = []
        for lo, hi in bounds:
            sub = [p for p in pairs
                   if p.case_id in cases and lo <= changed_lines(cases[p.case_id]) <= hi]
            label = f"{lo}-{hi} changed lines" if hi < 10 ** 9 else f"{lo}+ changed lines"
            groups.append((label, sub))
        emit("By CVE-fix size (changed-line quartile)", groups)


def analyse(run, cases):
    pairs = to_pairs(load_records(ROOT / "results" / run))
    if not pairs:
        return None
    s = M.summary(pairs)
    out = [f"# WP1 statistical rebuild - `{run}`", "",
           f"Source: `results/{run}/` ({s['n_cases']} records), read-only. "
           f"Generated by `experiments/2026-08-15_statistical-rebuild/run.py`.", ""]

    out.append("## 0. Reproduction gate")
    out.append("")
    ok = check_reproduction(run, s, out)
    out.append("")
    out.append("Reproduces the published report." if ok
               else "**Does not reproduce - stop and investigate before reading on.**")

    out.append("\n## 1. Headline metrics with clustered confidence intervals\n")
    out.append("Resampling unit is the **CVE**, not the case: the scored set spans "
               f"{len({p.cve_id for p in scored(pairs)})} CVEs over {len(scored(pairs))} "
               "cases, so a multi-function commit contributes several non-independent "
               "outcomes. Binomial CIs would be too narrow.\n")
    a = M.afc(pairs)
    rows = [
        ("Paired Flag Accuracy", M.pfa(pairs), M.cluster_bootstrap(pairs, M.pfa)),
        ("2AFC, ties excluded", a["tie_corrected"],
         M.cluster_bootstrap(pairs, lambda ps: M.afc(ps)["tie_corrected"])),
        ("ROC-AUC", M.auc(pairs), M.cluster_bootstrap(pairs, M.auc)),
    ]
    out.append("| Metric | Point estimate | 95% CI (CVE-clustered bootstrap) |")
    out.append("|---|---|---|")
    for name, val, ci in rows:
        fmt = (lambda x: f"{x:.3f}") if name == "ROC-AUC" else pct
        ci_s = f"[{fmt(ci['lo'])}, {fmt(ci['hi'])}]" if ci else "n/a"
        out.append(f"| {name} | {fmt(val)} | {ci_s} |")
    out.append(f"\nBootstrap: {rows[0][2]['n_boot']} resamples over "
               f"{rows[0][2]['n_clusters']} CVE clusters.")

    out.append("\n## 2. The tie correction\n")
    out.append(f"- Raw Pairwise Ranking Accuracy (ties = failure, as published): "
               f"**{pct(a['raw'])}**")
    out.append(f"- Tie rate: **{pct(a['tie_rate'])}** ({s['n_scored'] - a['n_untied']} "
               f"of {s['n_scored']} cases)")
    out.append(f"- 2AFC with ties excluded: **{pct(a['tie_corrected'])}** "
               f"(n={a['n_untied']}), against a 50% chance line")
    out.append("\nThe raw figure is not comparable to a 50% baseline, because a tie "
               "is scored as a loss rather than excluded. The tie-corrected figure is "
               "the one to report against chance; both belong in the paper.")

    out.append("\n## 3. Permutation test (replaces the independence baseline)\n")
    perm = M.permutation_test(pairs, M.pfa)
    fr = s["flag_rates"]
    out.append(f"Swapping the two judge verdicts within each case is exchangeable "
               f"under the null that the reference shown does not matter.\n")
    out.append(f"- Observed PFA: **{pct(perm['observed'])}**")
    out.append(f"- Permutation null: mean {pct(perm['null_mean'])}, "
               f"95% range [{pct(perm['null_lo95'])}, {pct(perm['null_hi95'])}] "
               f"over {perm['n_perm']} permutations")
    out.append(f"- p(null >= observed) = {perm['p_greater']:.4f}; "
               f"p(null <= observed) = {perm['p_less']:.4f}")
    out.append(f"- For comparison, the report's analytic independence baseline "
               f"({pct(fr['vulnerable'])} x (1 - {pct(fr['fixed'])})) = "
               f"**{pct(fr['independence_baseline'])}**")
    inside = perm["null_lo95"] <= perm["observed"] <= perm["null_hi95"]
    out.append(
        "\n**This corrects the experiment write-up's section 4.3(c).** That section "
        f"compares the observed {pct(perm['observed'])} against an analytic baseline of "
        f"{pct(fr['independence_baseline'])} built by multiplying the two marginal flag "
        "rates, concludes the detector performs *below chance*, and infers from the "
        "shortfall that the two judge calls must be positively correlated.\n\n"
        "The multiplication is only valid if the two calls are independent - the very "
        "thing the argument goes on to deny. The permutation null does not need that "
        "assumption: it swaps both verdicts together, so whatever correlation exists "
        "between the two calls is preserved inside the null. Its mean is "
        f"{pct(perm['null_mean'])}, not {pct(fr['independence_baseline'])}.")
    if inside:
        out.append(
            f"\nAgainst that correct null, the observed {pct(perm['observed'])} sits "
            f"**inside** the 95% range [{pct(perm['null_lo95'])}, {pct(perm['null_hi95'])}] "
            f"(p = {perm['p_less']:.3f}). The detector is therefore **not** below chance. "
            "The defensible claim is stronger and simpler: *paired flag accuracy is "
            "statistically indistinguishable from a null in which the reference shown to "
            "the judge has no effect on its verdict.* The paper should make that claim "
            "and drop the below-chance framing, which a reviewer would reject.")
    else:
        out.append(
            f"\nThe observed value falls outside the null 95% range "
            f"(p_less = {perm['p_less']:.4f}), so the below-chance reading survives the "
            "correct null and can be stated - citing this test rather than the "
            "marginal-product argument.")

    out.append("\n## 4. How far the score duplicates the category\n")
    mi = M.score_category_mi(pairs)
    mi_s = M.score_category_mi(scored(pairs))
    out.append(f"- Score histogram, all judge calls: {mi['score_histogram']}")
    out.append(f"- Score histogram, scored cases only: {mi_s['score_histogram']} "
               f"(**{mi_s['distinct_scores_used']} of 10** values ever used; "
               f"{pct(sum(v for k, v in mi_s['score_histogram'].items() if 2 <= k <= 5) / sum(mi_s['score_histogram'].values()))}"
               " of the mass sits in 2-5)")
    out.append(f"- H(score) = {mi['entropy_score_bits']:.3f} bits; "
               f"I(score; category) = {mi['mi_bits']:.3f} bits")
    out.append(f"- The category explains **{pct(mi['fraction_of_score_entropy_explained'])}** "
               "of the score's entropy")
    out.append(
        "\nThe rubric binds score ranges to categories (`.claude/agents/vuln-judge.md` "
        "steps 2-4), and that binding is visible: the category fixes most of the score, "
        "and on the scored subset the scale collapses onto a handful of values with a "
        "gap where 6-8 should be. ROC-AUC is therefore **substantially redundant with** "
        "Paired Flag Accuracy rather than independent evidence for it - the write-up's "
        "section 4.3(a)/(b)/(c) are better described as one demonstration examined three "
        "ways than as three independent ones. It is not a *complete* relabelling "
        f"({pct(1 - mi['fraction_of_score_entropy_explained'])} of the score's entropy is "
        "unexplained by category), so the AUC is not worthless - just not corroborating. "
        "WP5-R1 decouples the two so it can be.")

    out.append("\n## 5. Outcome distribution\n")
    out.append("| Outcome | Cases | Share |")
    out.append("|---|---|---|")
    for k, v in sorted(s["outcome_distribution"].items(), key=lambda kv: -kv[1]):
        out.append(f"| {k} | {v} | {pct(v / s['n_scored'])} |")
    ms = s["mean_scores"]
    out.append(f"\nMean judge score: vulnerable {ms['vulnerable']:.2f}, "
               f"fixed {ms['fixed']:.2f}, delta "
               f"**{ms['delta_fixed_minus_vulnerable']:+.2f}**.")

    out.append("\n## 6. Strata")
    strata_table(pairs, cases, out)

    out.append("\n## 7. Degenerate cases\n")
    out.append(f"Pooled `degenerate_generation`: {s['n_degenerate']}/{s['n_cases']} "
               f"({pct(s['degenerate_rate'])}), excluded from every figure above. "
               "See `scripts/analyze_degenerate.py` for the generator-vs-reference "
               "decomposition that reduces the genuine model-failure rate to 0.8%.")
    return "\n".join(out) + "\n"


def main():
    runs = sys.argv[1:] or ["qwen_full"]
    cases = load_cases()
    for run in runs:
        report = analyse(run, cases)
        if report is None:
            print(f"{run}: no records found, skipping")
            continue
        path = HERE / (f"report_{run}.md" if len(runs) > 1 else "report.md")
        path.write_text(report, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
        print()
        print(report)


if __name__ == "__main__":
    main()
